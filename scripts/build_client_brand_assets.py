"""Embed approved local artwork without changing the application's routes."""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'frontend' / 'index' / 'assets'
images = {}
for name, extension, mime in (
    ('city', 'jpg', 'image/jpeg'),
    ('research', 'jpg', 'image/jpeg'),
    ('collaboration', 'jpg', 'image/jpeg'),
    ('policy', 'png', 'image/png'),
):
    filename = 'policy-planning.png' if name == 'policy' else name + '.' + extension
    images[name] = 'data:' + mime + ';base64,' + base64.b64encode((ASSETS / filename).read_bytes()).decode('ascii')

output = '/* Generated by scripts/build_client_brand_assets.py; approved local artwork. */\n'
output += 'var HXZ_BRAND_IMAGES = Object.freeze(' + json.dumps(images, separators=(',', ':')) + ');\n'
output += "var HXZ_CARD_ART = Object.freeze([HXZ_BRAND_IMAGES.research,HXZ_BRAND_IMAGES.city,HXZ_BRAND_IMAGES.collaboration,HXZ_BRAND_IMAGES.policy]);\n"
output += "(function(){var style=document.documentElement&&document.documentElement.style;if(!style||typeof style.setProperty!=='function')return;['city','research','collaboration'].forEach(function(name){style.setProperty('--hxz-'+name+'-image','url(\"'+HXZ_BRAND_IMAGES[name]+'\")');});}());\n"
(ROOT / 'frontend' / 'index' / 'brand-assets.js').write_text(output)
print('Embedded 4 approved client images')
