"""Embed the small, local Qingxu brand images in the standalone admin page."""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'frontend' / 'ops' / 'assets'
items = []
for name in ('city', 'research', 'collaboration'):
    encoded = base64.b64encode((ASSETS / (name + '.jpg')).read_bytes()).decode('ascii')
    items.append("  '" + name + "': 'data:image/jpeg;base64," + encoded + "'")
output = "/* Generated by scripts/build_ops_brand_assets.py; local concept artwork. */\n"
output += "var OPS_BRAND_IMAGES = Object.freeze({\n" + ',\n'.join(items) + "\n});\n"
(ROOT / 'frontend' / 'ops' / 'brand-assets.js').write_text(output)
print('Embedded 3 local brand images')
