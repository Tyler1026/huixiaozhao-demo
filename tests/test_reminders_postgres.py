"""Real PostgreSQL reminder transactions, confined to a fresh test schema.

No DATABASE_URL fallback: CI supplies the dedicated local report_ci database.
The production postgres_session, snapshot writer, auth and reminder handlers run
unchanged. Only the connection DSN is scoped to this test's private schema.
"""
import concurrent.futures
import contextlib
import copy
import hashlib
import json
import os
import threading
import time
import unittest
import uuid
from unittest.mock import patch

from backend import reminders, storage
from backend.docking_actions import apply_docking_action
from backend.sync_transaction import postgres_session
from tests import test_reminders as fixtures


@unittest.skipUnless(os.environ.get('HXZ_TEST_DATABASE_URL'),
                     'isolated PostgreSQL CI fixture only; not exercised without HXZ_TEST_DATABASE_URL')
class ReminderPostgresTests(unittest.TestCase):
    def setUp(self):
        import psycopg2
        from psycopg2 import extensions, sql
        self.driver, self.sql = psycopg2, sql
        supplied = os.environ['HXZ_TEST_DATABASE_URL']
        parsed = extensions.parse_dsn(supplied)
        # Validate effective libpq settings, not just a URL hostname that a
        # query parameter/service file could override. Never log the DSN.
        self.assertFalse(os.environ.get('PGSERVICE'), 'PGSERVICE must be absent in the isolated test')
        self.assertFalse(os.environ.get('PGSERVICEFILE'), 'PGSERVICEFILE must be absent in the isolated test')
        self.assertIn(parsed.get('host'), ('localhost', '127.0.0.1'))
        self.assertEqual(parsed.get('dbname'), 'report_ci')
        self.assertNotIn('service', parsed)
        if parsed.get('hostaddr'):
            self.assertEqual(parsed['hostaddr'], '127.0.0.1')
        self.schema = 'reminder_pg_' + uuid.uuid4().hex
        # Explicit hostaddr/port prevent PGHOSTADDR/PGPORT environment defaults
        # from redirecting the validated localhost test connection.
        destination = {'hostaddr': '127.0.0.1', 'port': parsed.get('port') or '5432'}
        self.admin_dsn = extensions.make_dsn(supplied, **destination, options='-c search_path=pg_catalog',
                                              application_name=self.schema)
        self.dsn = extensions.make_dsn(supplied, **destination,
            options='-c search_path=' + self.schema + ',pg_catalog', application_name=self.schema)
        with contextlib.closing(self.driver.connect(self.admin_dsn, connect_timeout=3)) as connection:
            connection.autocommit = True
            with connection.cursor() as cursor:
                cursor.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(self.schema)))
        self.addCleanup(self._drop_schema)
        with self.connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute('CREATE TABLE sync_data (id INTEGER PRIMARY KEY, data TEXT NOT NULL, '
                               'updated_at TIMESTAMP DEFAULT NOW())')
                cursor.execute('CREATE TABLE sync_history (ts BIGINT PRIMARY KEY, data TEXT NOT NULL, '
                               'created_at TIMESTAMP DEFAULT NOW())')
                state = fixtures.authenticated(fixtures.fixture())
                token = 'B' * 43
                state['AUTH_SESSIONS'][hashlib.sha256(token.encode()).hexdigest()] = {
                    'user': 'bob', 'source': 'USER_PROFILES', 'active_projKey': 'b',
                    'credential_fingerprint': hashlib.sha256(b'fixture-b').hexdigest(),
                    'expires_at': (fixtures.NOW + 30 * 86400000) / 1000}
                cursor.execute('INSERT INTO sync_data(id,data) VALUES(1,%s)', (json.dumps(state),))
        self.pids, self.pid_lock = [], threading.Lock()
        # This is a DSN substitution, not a mocked session/driver/transaction.
        # postgres_session still opens and closes real independent connections.
        dsn_patch = patch.object(storage, 'DATABASE_URL', self.dsn)
        dsn_patch.start(); self.addCleanup(dsn_patch.stop)

    @contextlib.contextmanager
    def connection(self):
        with contextlib.closing(self.driver.connect(self.dsn, connect_timeout=3)) as connection:
            with connection:
                yield connection

    def _drop_schema(self):
        # Delete only the schema generated by this test instance. No TRUNCATE,
        # public-table mutation, database drop or shared-schema cleanup.
        with contextlib.closing(self.driver.connect(self.admin_dsn, connect_timeout=3)) as connection:
            connection.autocommit = True
            with connection.cursor() as cursor:
                cursor.execute(self.sql.SQL('DROP SCHEMA {} CASCADE').format(self.sql.Identifier(self.schema)))

    @contextlib.contextmanager
    def factory(self):
        with postgres_session() as session:
            with self.pid_lock:
                self.pids.append((threading.current_thread().name, session.connection.get_backend_pid()))
            self.assertEqual(session.connection.info.parameter_status('application_name'), self.schema)
            session.cursor.execute('SELECT current_schema()')
            self.assertEqual(session.cursor.fetchone()[0], self.schema)
            yield session

    def read_bytes(self):
        with self.connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute('SELECT data FROM sync_data WHERE id=1')
                return cursor.fetchone()[0]

    def read(self):
        return json.loads(self.read_bytes())

    def send(self, operation='get', body=None, *, now=None, user='alice', on_ack=None, factory=None):
        class Response(fixtures.Handler):
            def send_response(inner, status):
                if status == 200 and on_ack:
                    on_ack()
                super().send_response(status)
        handler = Response('/api/reminders?projectKey=a&requestId=postgres-get')
        if user == 'bob':
            handler.headers['Cookie'] = fixtures.SESSION_COOKIE_NAME + '=' + 'B' * 43
        reminders.handle_request(handler, json.dumps(body).encode() if body is not None else b'',
            factory or self.factory, operation=operation, now=fixtures.NOW if now is None else now)
        return handler.status, handler.result

    def test_false_preferences_commit_before_ack_and_survive_new_connection(self):
        before = self.read()
        status, loaded = self.send()
        self.assertEqual(status, 200)
        acknowledgements = []
        def acknowledged():
            # Executed at HTTP send_response(200), using another PG connection.
            account = next(iter(self.read()[reminders.TABLE].values()))
            self.assertEqual(account['preferences'], dict.fromkeys(reminders.DEFAULTS, False))
            self.assertEqual(account['version'], 1)
            acknowledgements.append(True)
        status, saved = self.send('preferences', fixtures.follow(loaded,
            preferences=dict.fromkeys(reminders.DEFAULTS, False)), now=fixtures.NOW + 1, on_ack=acknowledged)
        self.assertEqual(status, 200)
        self.assertEqual(acknowledgements, [True])
        status, reloaded = self.send(now=fixtures.NOW + 2)
        self.assertEqual(status, 200)
        self.assertEqual(reloaded['preferences'], saved['preferences'])
        self.assertEqual((reloaded['accountEpoch'], reloaded['version']), (saved['accountEpoch'], 1))
        self.assertEqual({key: value for key, value in self.read().items() if key != reminders.TABLE}, before)
        self.assertNotIn('credential', json.dumps(saved))

    def test_unauthorized_and_stale_version_leave_snapshot_bytes_unchanged(self):
        status, loaded = self.send()
        self.assertEqual(status, 200)
        status, saved = self.send('preferences', fixtures.follow(loaded,
            preferences=dict.fromkeys(reminders.DEFAULTS, False)), now=fixtures.NOW + 1)
        self.assertEqual(status, 200)
        before = self.read_bytes()
        status, denied = self.send('preferences', fixtures.follow(saved,
            preferences=copy.deepcopy(reminders.DEFAULTS)), user='bob', now=fixtures.NOW + 2)
        self.assertEqual(status, 403)
        self.assertFalse(denied['ok'])
        self.assertEqual(self.read_bytes(), before)
        status, stale = self.send('preferences', fixtures.follow(loaded,
            preferences=copy.deepcopy(reminders.DEFAULTS)), now=fixtures.NOW + 3)
        self.assertEqual(status, 409)
        self.assertFalse(stale['ok'])
        self.assertEqual(self.read_bytes(), before)

    def test_aborted_postgres_transaction_returns_failure_and_rolls_back(self):
        _, loaded = self.send()
        before = self.read_bytes()
        @contextlib.contextmanager
        def aborted():
            with self.factory() as session:
                try:
                    session.cursor.execute('SELECT 1 / 0')
                except self.driver.Error:
                    pass
                yield session
        status, failed = self.send('preferences', fixtures.follow(loaded,
            preferences=dict.fromkeys(reminders.DEFAULTS, False)), factory=aborted)
        self.assertEqual(status, 503)
        self.assertFalse(failed['ok'])
        self.assertEqual(self.read_bytes(), before)

    def _wait_for_competing_locks(self, count):
        deadline = time.monotonic() + 3
        while time.monotonic() < deadline:
            with self.connection() as connection:
                with connection.cursor() as cursor:
                    cursor.execute("SELECT COUNT(*) FROM pg_stat_activity "
                                   "WHERE application_name=%s AND wait_event_type='Lock'", (self.schema,))
                    waiting = cursor.fetchone()[0]
            if waiting == count:
                return
            time.sleep(.01)
        self.fail('Reminder HTTP write and both worker connections did not contend for the test row lock')

    def test_preferences_and_two_ticks_serialize_without_duplicate_event_or_daily(self):
        _, loaded = self.send()
        with self.factory() as session:
            state = json.loads(session.read())
            result = apply_docking_action({'projectKey': 'd', 'action': 'review_demand',
                'requestId': 'postgres-intake', 'expectedVersion': 0,
                'record': {'status': 'processing', 'owner': 'offline-ops',
                           'nextStep': 'Review test materials', 'note': 'Synthetic persisted intake'}},
                state, {'scope': 'admin', 'user': 'offline-ops'}, now=fixtures.NOW + 1)
            event_id = result['logs'][0]['id']
            self.assertTrue(session.write(json.dumps(state)))
        tick_time = fixtures.stamp('2026-10-24T09:00:00')
        selected = dict(reminders.DEFAULTS, overdue=False)
        barrier = threading.Barrier(4)
        def preferences():
            barrier.wait(timeout=3)
            return self.send('preferences', fixtures.follow(loaded, preferences=selected), now=tick_time)
        def tick():
            barrier.wait(timeout=3)
            reminders.run_once(self.factory, now=tick_time)
        with concurrent.futures.ThreadPoolExecutor(max_workers=3, thread_name_prefix='reminder-pg-worker') as pool:
            # Holding the real row lock makes all three independent connections
            # contend before release, rather than merely starting at similar times.
            with self.factory():
                self.pids.clear()
                saved_future = pool.submit(preferences)
                workers = [pool.submit(tick) for _ in range(2)]
                barrier.wait(timeout=3)
                self._wait_for_competing_locks(3)
            status, saved = saved_future.result(timeout=8)
            for worker in workers:
                worker.result(timeout=8)
        self.assertEqual(status, 200)
        self.assertEqual(saved['version'], 1)
        self.assertEqual(saved['preferences'], selected)
        worker_pids = {pid for name, pid in self.pids if name.startswith('reminder-pg-worker')}
        self.assertEqual(len(worker_pids), 3)
        status, after = self.send(now=tick_time + 1)
        self.assertEqual(status, 200)
        self.assertEqual(after['version'], saved['version'])
        self.assertEqual(after['accountEpoch'], saved['accountEpoch'])
        self.assertEqual(after['notifications'], saved['notifications'])
        self.assertEqual(len(after['notifications']), 2)
        self.assertEqual({notice['type'] for notice in after['notifications']}, {'status', 'daily'})
        source_ids = [notice['sourceId'] for notice in after['notifications']]
        self.assertEqual(len(source_ids), len(set(source_ids)))
        self.assertIn('d:dock:' + event_id, source_ids)
        account = next(iter(self.read()[reminders.TABLE].values()))
        self.assertEqual(len(account['workspaces']['a']['notifications']), 2)


if __name__ == '__main__':
    unittest.main()
